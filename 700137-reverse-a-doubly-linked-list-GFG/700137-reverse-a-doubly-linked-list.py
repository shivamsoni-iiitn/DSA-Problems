"""
Structure of doubly linked list node
class Node:
    def __init__(self, val):
        self.data = val
        self.next = None
        self.prev = None
"""

class Solution:
    def reverse(self, head):
        # code here
        curr=head
        while curr!=None:
            curr.next,curr.prev=curr.prev, curr.next
            if curr!=None:   
                head=curr
            curr=curr.prev
            
        return head
        

